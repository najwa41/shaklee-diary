const CACHE_NAME = 'shaklee-diary-v1';
const ASSETS = [
  './',
  './index.html',
  './manifest.json',
  './logo.jpg.PNG',
  './sync.js',
  './tema.js'
];

// Install: Simpan fail-fail ke dalam phone
self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(ASSETS))
  );
  self.skipWaiting();
});

// Activate: Buang cache lama kalau ada update baru
self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(
        keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k))
      )
    )
  );
  self.clients.claim();
});

// Fetch: Cuba ambil dari internet dulu. Kalau takda internet, ambil dari simpanan (cache)
self.addEventListener('fetch', (event) => {
  if (event.request.method !== 'GET') return;
  event.respondWith(
    fetch(event.request)
      .then((response) => {
        const clone = response.clone();
        caches.open(CACHE_NAME).then((cache) => {
          cache.put(event.request, clone);
        });
        return response;
      })
      .catch(() => caches.match(event.request))
  );
});
